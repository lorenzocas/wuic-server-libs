    "SELECT s.[id] AS [id], s.[fattura_inviata_id] AS [fattura_inviata_id], "
    "s.[rata_n] AS [rata_n], s.[rata_totale] AS [rata_totale], "
    "s.[data_scadenza] AS [data_scadenza], s.[importo] AS [importo], "
    "s.[stato] AS [stato], "
    "ISNULL(pg.[descrizione], '') AS [pagamento_descrizione], "
    "ISNULL(b.[descrizione], '')  AS [banca_descrizione], "
    "ISNULL(b.[iban], '')         AS [banca_iban], "
    "ISNULL(b.[bic_swift], '')    AS [banca_bic] "
    "FROM [FatturazioneElettronica_Data].[dbo].[scadenze] s "
    "LEFT JOIN [FatturazioneElettronica_Data].[dbo].[pagamenti] pg ON s.pagamento_id = pg.id "
    "LEFT JOIN [FatturazioneElettronica_Data].[dbo].[banche] b    ON s.banca_id     = b.id "
