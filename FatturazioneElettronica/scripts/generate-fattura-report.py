# Aggregato IVA (group by aliquota+natura) — calcolato da `fatture_inviate_righe`.
SQL_RIEPILOGO_IVA = (
    "SELECT "
    "ISNULL(ci.[aliquota], 0)  AS aliquota, "
    "ISNULL(ci.[natura_sdi], '') AS natura_sdi, "
    "ISNULL(ci.[descrizione], '') AS natura_descr, "
    "SUM(r.imponibile_riga)    AS imponibile_tot, "
    "SUM(r.iva_riga)           AS iva_tot "
    "FROM [FatturazioneElettronica_Data].[dbo].[fatture_inviate_righe] r "
    "LEFT JOIN [FatturazioneElettronica_Data].[dbo].[codici_iva] ci ON r.codice_iva_id = ci.id "
    "WHERE r.fattura_id = @fattura_id "
    "GROUP BY ci.aliquota, ci.natura_sdi, ci.descrizione "
    "ORDER BY ci.aliquota DESC, ci.natura_sdi"
)

# ── Helpers ─────────────────────────────────────────────────────────────

def encode_logo_b64() -> str:
    if not LOGO_PATH.exists():
        raise FileNotFoundError(f"Logo non trovato: {LOGO_PATH}")
    with open(LOGO_PATH, 'rb') as fh:
        return base64.b64encode(fh.read()).decode('ascii')


def text_component(name: str, x, y, w, h, expr: str, *,
                   font='Arial,8', font_bold=False,
                   align='Left', valign='Center',
                   bg='Transparent', border='None;Black;1;Solid;False;4;Black',
                   text_color='Black', is_expression=True,
                   parent_ref: int, page_ref: int = 8,
                   ref: int) -> str:
    """Generate a <Text> component XML block."""
    font_full = font + (',Bold' if font_bold else '')
    typ = 'Expression' if is_expression else 'Text'
    xml_text = expr.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    return dedent(f"""
        <{name} Ref="{ref}" type="Text" isKey="true">
          <Border>{border}</Border>
          <Brush>{bg}</Brush>
          <ClientRectangle>{x},{y},{w},{h}</ClientRectangle>
          <Conditions isList="true" count="0" />
          <Expressions isList="true" count="0" />
          <Font>{font_full}</Font>
          <HorAlignment>{align}</HorAlignment>
          <Name>{name}</Name>
          <Page isRef="{page_ref}" />
          <Parent isRef="{parent_ref}" />
          <Text>{xml_text}</Text>
          <TextBrush>{text_color}</TextBrush>
          <Type>{typ}</Type>
          <VertAlignment>{valign}</VertAlignment>
          <WordWrap>True</WordWrap>
          <CanGrow>True</CanGrow>
        </{name}>""").strip()


def image_component(name: str, x, y, w, h, image_b64: str, *,
                    parent_ref: int, page_ref: int = 8, ref: int) -> str:
    return dedent(f"""
        <{name} Ref="{ref}" type="Image" isKey="true">
          <AspectRatio>True</AspectRatio>
          <Border>None;Black;1;Solid;False;4;Black</Border>
          <Brush>Transparent</Brush>
          <ClientRectangle>{x},{y},{w},{h}</ClientRectangle>
          <Conditions isList="true" count="0" />
          <Expressions isList="true" count="0" />
          <Image>{image_b64}</Image>
          <Name>{name}</Name>
          <Page isRef="{page_ref}" />
          <Parent isRef="{parent_ref}" />
          <Stretch>True</Stretch>
        </{name}>""").strip()


